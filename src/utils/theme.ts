export function getThemeColors(themeKey?: StoreTheme, mode: ThemeMode = 'light'): ThemeColors {
  const tKey = themeKey && THEME_TEMPLATES[themeKey] ? themeKey : 'royal_crimson';
  const tmpl = THEME_TEMPLATES[tKey] || THEME_TEMPLATES.royal_crimson;
  return mode === 'dark' ? tmpl.dark : tmpl.light;
}

